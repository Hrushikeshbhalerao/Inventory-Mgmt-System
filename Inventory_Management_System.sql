DROP DATABASE IF EXISTS Inventory_DB;
CREATE DATABASE Inventory_DB;
USE Inventory_DB;

CREATE TABLE suppliers (
  supplier_id INT PRIMARY KEY,
  supplier_name VARCHAR(100) NOT NULL,
  contact_name VARCHAR(100),
  phone VARCHAR(20),
  city VARCHAR(60),
  email VARCHAR(120),
  active TINYINT(1) NOT NULL DEFAULT 1
);

CREATE TABLE products (
  product_id INT PRIMARY KEY,
  product_name VARCHAR(120) NOT NULL,
  category VARCHAR(60) NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL,
  stock_quantity INT NOT NULL DEFAULT 0,
  reorder_level INT NOT NULL DEFAULT 10,
  supplier_id INT NOT NULL,
  created_at DATE NOT NULL,
  CONSTRAINT fk_product_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id)
);

CREATE TABLE inventory (
  transaction_id INT PRIMARY KEY,
  product_id INT NOT NULL,
  transaction_type ENUM('IN','OUT','ADJUSTMENT') NOT NULL,
  quantity INT NOT NULL,
  transaction_date DATE NOT NULL,
  reference_note VARCHAR(150),
  CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES products(product_id)
);

CREATE TABLE purchase_orders (
  po_id INT PRIMARY KEY,
  supplier_id INT NOT NULL,
  order_date DATE NOT NULL,
  expected_date DATE NOT NULL,
  status ENUM('Pending','Received','Cancelled') NOT NULL,
  CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id)
);

CREATE TABLE purchase_order_items (
  po_item_id INT PRIMARY KEY,
  po_id INT NOT NULL,
  product_id INT NOT NULL,
  quantity INT NOT NULL,
  unit_cost DECIMAL(10,2) NOT NULL,
  CONSTRAINT fk_poi_order FOREIGN KEY (po_id) REFERENCES purchase_orders(po_id),
  CONSTRAINT fk_poi_product FOREIGN KEY (product_id) REFERENCES products(product_id)
);


